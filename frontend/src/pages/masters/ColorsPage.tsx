// src/pages/masters/ColorsPage.tsx
import React, { useEffect, useState } from 'react';
import { api } from '../../lib/api';
import PageHeader from '../../components/ui/PageHeader';
import DataTable from '../../components/ui/DataTable';
import StatusBadge from '../../components/ui/StatusBadge';
import Modal from '../../components/ui/Modal';
import Button from '../../components/ui/Button';
import FormField from '../../components/ui/FormField';
import PantoneColorPicker from '../../components/ui/PantoneColorPicker';
import { Plus, Edit2, Trash2, AlertCircle, RefreshCw, Palette } from 'lucide-react';

interface ColorRecord {
  id: number;
  code?: string;
  name: string;
  hex_code: string;
  pantone_code?: string;
  status?: string;
}

export default function ColorsPage() {
  const [colors, setColors] = useState<ColorRecord[]>([]);
  const [loading, setLoading] = useState(true);
  const [modalOpen, setModalOpen] = useState(false);
  const [editColor, setEditColor] = useState<ColorRecord | null>(null);
  const [saving, setSaving] = useState(false);
  const [error, setError] = useState('');
  const [form, setForm] = useState({ code: '', name: '', hex_code: '#0f2042', pantone_code: '', status: 'active' });

  // Delete modal state
  const [deleteColorItem, setDeleteColorItem] = useState<ColorRecord | null>(null);
  const [deleting, setDeleting] = useState(false);
  const [deleteError, setDeleteError] = useState('');

  const loadData = () => {
    setLoading(true);
    api.getColors()
      .then(d => setColors((d || []) as ColorRecord[]))
      .catch(() => setColors([]))
      .finally(() => setLoading(false));
  };

  useEffect(() => {
    loadData();
  }, []);

  const openCreate = () => {
    setEditColor(null);
    setForm({ code: '', name: '', hex_code: '#0f2042', pantone_code: '', status: 'active' });
    setError('');
    setModalOpen(true);
  };

  const openEdit = (c: ColorRecord) => {
    setEditColor(c);
    setForm({
      code: c.code || '',
      name: c.name,
      hex_code: c.hex_code || '#0f2042',
      pantone_code: c.pantone_code || '',
      status: c.status || 'active'
    });
    setError('');
    setModalOpen(true);
  };

  const handlePantoneSelect = (item: { pantone_code: string; name: string; hex_code: string }) => {
    setForm(prev => ({
      ...prev,
      pantone_code: item.pantone_code,
      name: item.name,
      hex_code: item.hex_code
    }));
  };

  const handleSave = async () => {
    if (!form.name.trim()) {
      setError('Color name is required');
      return;
    }
    setSaving(true);
    setError('');
    const normalizedPantone = form.pantone_code.trim().toUpperCase();

    try {
      if (editColor) {
        await api.updateColor(editColor.id, {
          name: form.name.trim(),
          code: form.code.trim(),
          hex_code: form.hex_code,
          pantone_code: normalizedPantone,
          status: form.status
        });
      } else {
        await api.createColor({
          name: form.name.trim(),
          code: '', // Auto-generated by backend (CLR-XXXX)
          hex_code: form.hex_code,
          pantone_code: normalizedPantone
        });
      }
      setModalOpen(false);
      loadData();
    } catch (e: unknown) {
      setError((e as Error).message || 'Failed to save color');
    } finally {
      setSaving(false);
    }
  };

  const confirmDelete = async () => {
    if (!deleteColorItem) return;
    setDeleting(true);
    setDeleteError('');
    try {
      await api.deleteColor(deleteColorItem.id);
      setDeleteColorItem(null);
      loadData();
    } catch (e: unknown) {
      setDeleteError((e as Error).message || 'Failed to delete color. It may be referenced in orders.');
    } finally {
      setDeleting(false);
    }
  };

  const columns = [
    {
      key: 'code',
      label: 'Internal Code',
      sortable: true,
      width: '120px',
      render: (r: ColorRecord) => (
        <span className="font-mono text-[11px] font-bold text-slate-700 bg-slate-100 px-2 py-0.5 rounded border border-slate-200">
          {r.code || `CLR-${String(r.id).padStart(4, '0')}`}
        </span>
      )
    },
    {
      key: 'name',
      label: 'Color Name',
      sortable: true,
      render: (r: ColorRecord) => (
        <div className="flex items-center gap-2.5">
          <div
            className="w-5 h-5 rounded-md border border-slate-300 shrink-0 shadow-2xs"
            style={{ backgroundColor: r.hex_code || '#64748b' }}
            title={r.hex_code || '#64748b'}
          />
          <span className="font-semibold text-slate-800 text-xs">{r.name}</span>
        </div>
      )
    },
    {
      key: 'pantone_code',
      label: 'Pantone Color Code',
      sortable: true,
      render: (r: ColorRecord) => r.pantone_code ? (
        <span className="inline-flex items-center gap-1.5 px-2.5 py-1 bg-amber-50 border border-amber-200 rounded-md text-xs font-mono font-bold text-amber-900 shadow-2xs">
          <span className="w-2.5 h-2.5 rounded-xs shrink-0 border border-amber-300" style={{ backgroundColor: r.hex_code || '#D4A017' }} />
          {r.pantone_code}
        </span>
      ) : (
        <span className="text-slate-400 text-xs italic">Not assigned</span>
      )
    },
    {
      key: 'status',
      label: 'Status',
      width: '90px',
      render: (r: ColorRecord) => <StatusBadge status={r.status || 'active'} />
    },
  ];

  return (
    <div className="flex flex-col h-full">
      <PageHeader
        title="Colors Master"
        subtitle="Manage textile Pantone color codes and official color specifications"
        breadcrumb={[{ label: 'Masters' }, { label: 'Colors' }]}
        actions={
          <div className="flex gap-2">
            <button
              onClick={loadData}
              disabled={loading}
              className="flex items-center gap-1.5 px-2.5 py-1.5 text-xs border border-slate-200 rounded-md hover:bg-slate-50 transition-colors"
              title="Refresh Colors"
            >
              <RefreshCw className={`w-3.5 h-3.5 ${loading ? 'animate-spin' : ''}`} />
            </button>
            <Button icon={<Plus className="w-3.5 h-3.5" />} onClick={openCreate}>
              Add Color
            </Button>
          </div>
        }
      />

      <div className="flex-1 overflow-auto p-4">
        <DataTable
          data={colors}
          columns={columns}
          rowKey="id"
          actions={(r: ColorRecord) => (
            <div className="flex items-center gap-1">
              <button
                onClick={() => openEdit(r)}
                className="p-1.5 text-slate-500 hover:text-brand-600 rounded hover:bg-slate-100 transition-colors"
                title="Edit Color"
              >
                <Edit2 className="w-3.5 h-3.5" />
              </button>
              <button
                onClick={() => {
                  setDeleteColorItem(r);
                  setDeleteError('');
                }}
                className="p-1.5 text-slate-400 hover:text-red-600 rounded hover:bg-red-50 transition-colors"
                title="Delete Color"
              >
                <Trash2 className="w-3.5 h-3.5" />
              </button>
            </div>
          )}
        />
      </div>

      {/* Add / Edit Color Modal */}
      <Modal
        open={modalOpen}
        onClose={() => setModalOpen(false)}
        title={editColor ? `Edit Color: ${editColor.name}` : 'Add New Pantone Color'}
        size="md"
      >
        <div className="space-y-4">
          {error && (
            <div className="p-3 bg-red-50 border border-red-200 rounded-lg text-xs text-red-700 flex items-start gap-2">
              <AlertCircle className="w-4 h-4 shrink-0 mt-0.5" />
              <span>{error}</span>
            </div>
          )}

          {/* Pantone Selection Component */}
          <div>
            <label className="text-xs font-bold text-slate-700 block mb-1.5 flex items-center gap-1.5">
              <Palette className="w-3.5 h-3.5 text-brand-600" />
              <span>Select Textile Pantone Reference</span>
            </label>
            <PantoneColorPicker
              selectedPantone={form.pantone_code}
              selectedName={form.name}
              selectedHex={form.hex_code}
              onSelect={handlePantoneSelect}
            />
          </div>

          <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 pt-1">
            {/* Pantone Color Code */}
            <FormField
              label="Pantone Color Code"
              required
              hint="e.g. 19-4052 TCX, 18-1662 TCX"
              value={form.pantone_code}
              onChange={e => setForm(f => ({ ...f, pantone_code: e.target.value.toUpperCase() }))}
              placeholder="e.g. 19-4052 TCX"
            />

            {/* Official Color Name */}
            <FormField
              label="Color Name"
              required
              hint="Official textile name or brand color"
              value={form.name}
              onChange={e => setForm(f => ({ ...f, name: e.target.value }))}
              placeholder="e.g. Classic Navy"
            />
          </div>

          {/* Swatch Display */}
          <div className="p-3 bg-slate-50 border border-slate-200 rounded-lg flex items-center justify-between gap-3">
            <div>
              <span className="text-[11px] font-semibold text-slate-700 block">Digital Swatch Reference</span>
              <span className="text-[10px] text-slate-500">Representative digital color for UI cards and badges</span>
            </div>
            <div className="flex items-center gap-2">
              <input
                type="color"
                className="w-8 h-8 rounded border border-slate-300 cursor-pointer p-0.5 bg-white shadow-2xs"
                value={form.hex_code || '#0f2042'}
                onChange={e => setForm(f => ({ ...f, hex_code: e.target.value }))}
                title="Adjust digital preview swatch"
              />
              <span className="text-[11px] font-mono text-slate-600 font-semibold">{form.hex_code}</span>
            </div>
          </div>

          <div className="flex justify-end gap-2 pt-3 border-t border-slate-100">
            <Button variant="secondary" onClick={() => setModalOpen(false)}>
              Cancel
            </Button>
            <Button onClick={handleSave} disabled={saving}>
              {saving ? 'Saving...' : editColor ? 'Update Color' : 'Save Color'}
            </Button>
          </div>
        </div>
      </Modal>

      {/* Delete Confirmation Modal */}
      <Modal
        open={!!deleteColorItem}
        onClose={() => setDeleteColorItem(null)}
        title="Delete Color Confirmation"
        size="sm"
      >
        <div className="space-y-4">
          {deleteError && (
            <div className="p-3 bg-red-50 border border-red-200 rounded-lg text-xs text-red-700 flex items-start gap-2">
              <AlertCircle className="w-4 h-4 shrink-0 mt-0.5" />
              <div className="flex-1 leading-relaxed">{deleteError}</div>
            </div>
          )}

          <p className="text-xs text-slate-600 leading-relaxed">
            Are you sure you want to delete the color{' '}
            <strong className="text-slate-800 font-semibold">{deleteColorItem?.name}</strong>{' '}
            (<span className="font-mono font-bold text-slate-700">{deleteColorItem?.code || `CLR-${deleteColorItem?.id}`}</span>)?
          </p>

          {deleteColorItem?.pantone_code && (
            <div className="p-2.5 bg-amber-50 border border-amber-200 rounded-lg text-xs flex items-center gap-2">
              <span className="w-3 h-3 rounded-xs shrink-0 border border-amber-300" style={{ backgroundColor: deleteColorItem.hex_code }} />
              <span className="font-mono font-semibold text-amber-900">{deleteColorItem.pantone_code}</span>
            </div>
          )}

          <div className="p-2.5 bg-slate-50 border border-slate-200 rounded-lg text-[11px] text-slate-500">
            <strong>Referential Protection:</strong> Colors referenced in existing production orders or purchase orders cannot be deleted in order to preserve historical batch integrity.
          </div>

          <div className="flex justify-end gap-2 pt-2 border-t border-slate-100">
            <Button variant="secondary" onClick={() => setDeleteColorItem(null)} disabled={deleting}>
              Cancel
            </Button>
            <Button variant="danger" onClick={confirmDelete} loading={deleting}>
              Delete Color
            </Button>
          </div>
        </div>
      </Modal>
    </div>
  );
}
